// world-atlas's 50m topology does include a Kosovo polygon, but Kosovo has
// no ISO 3166-1 numeric code (it's not universally recognized), so the
// feature carries `id: undefined` instead of a real country code — the same
// bucket several other disputed/dependent territories with no code fall
// into (Somaliland, Northern Cyprus, ...), none of which are in our own
// country set. WorldMap.tsx drops all of those unconditionally, since id
// alone can't tell them apart and none of them should render as-is.
//
// Kosovo is genuinely in our 197-country set, though, and its polygon here
// is real, recognizable geography (verified by rendering it) — just filed
// under the wrong id. Rather than lose it entirely, this is that same ring,
// copied out and re-attached to a real id (see WorldMap.tsx's KOSOVO_FEATURE
// and countries.ts's KOSOVO_CCN3) so it renders like any other country
// instead of falling back to a marker dot.
//
// One caveat worth knowing about: Kosovo's boundary here wasn't drawn as
// part of the same shared-edge topology mesh as its neighbors (most
// adjacent countries in this dataset share exact border coordinates;
// Kosovo's was digitized independently), so it doesn't perfectly coincide
// with Serbia's own boundary — about 22% of Kosovo's boundary points land
// fractionally inside Serbia's polygon. In practice this is a normal,
// near-invisible sliver-overlap artifact of combining two independently-
// sourced boundaries (Serbia's shape isn't clipped to make room for it) —
// nothing like the same-color double-paint bug this was pulled out to fix.
//
// Sourced by extracting `Kosovo`'s own coordinates straight from the
// installed world-atlas@2.0.2 countries-50m.json via topojson-client — not
// hand-drawn, not from a different dataset.
